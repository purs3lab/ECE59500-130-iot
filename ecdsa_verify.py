"""
MicroPython has no ECDSA support at all (ucryptolib only provides AES) and
no SHA-256-over-arbitrary-message-then-EC-math primitive, so this vendors a
minimal pure-Python ECDSA verify for NIST P-256 (secp256r1) - the same
curve+hash Web Crypto uses for {name:'ECDSA', namedCurve:'P-256',
hash:'SHA-256'}. Matches what the webapp produces directly: a raw
uncompressed public key point (0x04||X||Y, 65 bytes) and a raw r||s
signature (64 bytes) - no ASN.1/DER anywhere on either side.

Curve constants below were extracted directly from
`openssl ecparam -name prime256v1 -param_enc explicit -text` (not
hand-transcribed) and cross-checked against the published NIST P-256
values before being used here.

verify() is deliberately not constant-time: every input (public key,
message, signature) is public data by the time it runs, so there's no
secret to leak via timing. That's different from PIN/pairing-code checks
(see constant_time_compare in common.py), which compare a secret against
attacker input and do need to be constant-time. sign() is a different
story - it operates on the device's private key - but this is a
teaching vendoring of the standard (non-constant-time) SEC1 algorithm, not
a hardened implementation; real timing/power side-channel resistance
(blinding, constant-time scalar mult) is explicitly out of scope, same
spirit as the BLE-relay non-goal in part2's README.md#unlock.

Attribution: generated by Claude (Anthropic), not copied from an existing
library. The verify algorithm and curve constants implement these public
specifications:
  - SEC 1: Elliptic Curve Cryptography, Certicom Research, v2.0 (2009) -
    the ECDSA verify algorithm (modular inverse, u1/u2, r == x mod n check).
  - SEC 2: Recommended Elliptic Curve Domain Parameters, Certicom Research -
    section 2.7, the P-256 (secp256r1) curve constants (p, a, b, G, n).
  - FIPS 186-5, Digital Signature Standard (DSS), NIST - the standard
    defining ECDSA and approving P-256 as a curve.
Curve constants were cross-checked by running
`openssl ecparam -name prime256v1 -param_enc explicit -text -noout` and
comparing its output against the published NIST P-256 values, rather than
hand-transcribing them. Correctness of the verify() function itself was
checked by generating real P-256 keys/signatures with OpenSSL and
confirming verify() both accepts genuine signatures and rejects tampered
messages/signatures/public keys. sign() (added for device attestation)
follows the same SEC1 signing algorithm and was checked the same way, in
reverse: signing with sign() and verifying the result with OpenSSL.
"""

import hashlib
import os

_P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
_A = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFC
_B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
_GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
_GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

_INF = None  # point at infinity


def _inverse_mod(k, m):
    # Extended Euclidean algorithm - avoids relying on the three-arg pow()
    # with a negative exponent for modular inverse, which older/smaller
    # MicroPython builds may not support.
    if k == 0:
        raise ZeroDivisionError("division by zero")
    if k < 0:
        return m - _inverse_mod(-k, m)
    old_r, r = k, m
    old_s, s = 1, 0
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
    return old_s % m


def _is_on_curve(point):
    if point is _INF:
        return True
    x, y = point
    return (y * y - (x * x * x + _A * x + _B)) % _P == 0


def _point_add(p1, p2):
    if p1 is _INF:
        return p2
    if p2 is _INF:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and (y1 + y2) % _P == 0:
        return _INF
    if p1 == p2:
        m = (3 * x1 * x1 + _A) * _inverse_mod(2 * y1, _P) % _P
    else:
        m = (y2 - y1) * _inverse_mod(x2 - x1, _P) % _P
    x3 = (m * m - x1 - x2) % _P
    y3 = (m * (x1 - x3) - y1) % _P
    return (x3, y3)


def _scalar_mult(k, point, feed_cb=None):
    if k % _N == 0 or point is _INF:
        return _INF
    if k < 0:
        return _scalar_mult(-k, (point[0], (-point[1]) % _P), feed_cb)
    result = _INF
    addend = point
    while k:
        if feed_cb is not None:
            feed_cb()
        if k & 1:
            result = _point_add(result, addend)
        addend = _point_add(addend, addend)
        k >>= 1
    return result


def verify(pubkey_bytes, message_bytes, signature_bytes, feed_cb=None):
    """pubkey_bytes: raw 0x04||X||Y (65 bytes). signature_bytes: raw r||s
    (64 bytes). message_bytes: the exact bytes that were signed - this
    function hashes them with SHA-256 itself, matching Web Crypto's
    hash:'SHA-256' behavior, so callers must NOT pre-hash.

    feed_cb: optional zero-arg callable invoked periodically during the
    slow scalar-multiplication step (e.g. a hardware watchdog's .feed()) -
    see _scalar_mult()."""
    if len(pubkey_bytes) != 65 or pubkey_bytes[0] != 0x04:
        return False
    if len(signature_bytes) != 64:
        return False

    qx = int.from_bytes(pubkey_bytes[1:33], "big")
    qy = int.from_bytes(pubkey_bytes[33:65], "big")
    q = (qx, qy)
    if not _is_on_curve(q):
        return False

    r = int.from_bytes(signature_bytes[0:32], "big")
    s = int.from_bytes(signature_bytes[32:64], "big")
    if not (1 <= r <= _N - 1 and 1 <= s <= _N - 1):
        return False

    z = int.from_bytes(hashlib.sha256(message_bytes).digest(), "big")

    w = _inverse_mod(s, _N)
    u1 = (z * w) % _N
    u2 = (r * w) % _N
    point = _point_add(_scalar_mult(u1, (_GX, _GY), feed_cb), _scalar_mult(u2, q, feed_cb))
    if point is _INF:
        return False
    return (point[0] % _N) == r


def sign(private_key, message_bytes, feed_cb=None):
    """private_key: the device's raw P-256 private scalar, an int with
    1 <= private_key <= N-1 (see load_device_private_key() in common.py).
    message_bytes: the exact bytes to sign - this function hashes them with
    SHA-256 itself, matching verify()'s behavior, so callers must NOT
    pre-hash. Returns a raw r||s signature (64 bytes), the same format
    verify() and the webapp's crypto.subtle.sign() produce.

    Every signature needs a fresh, secret, unpredictable per-signature
    nonce k (see the loop below) - reusing k across two signatures from the
    same key, or k being guessable, leaks the private key outright (this is
    exactly how the PS3 root key was recovered in 2010: Sony reused a fixed
    k for every signature). k is drawn from os.urandom here, the same CSPRNG
    source get_salt()/get_input_string() rely on elsewhere in this
    codebase - never a counter, timestamp, or anything derived from public
    data.
    """
    z = int.from_bytes(hashlib.sha256(message_bytes).digest(), "big")
    while True:
        k = int.from_bytes(os.urandom(32), "big") % _N
        if k == 0:
            continue
        point = _scalar_mult(k, (_GX, _GY), feed_cb)
        if point is _INF:
            continue
        assert point is not None
        r = point[0] % _N
        if r == 0:
            continue
        s = (_inverse_mod(k, _N) * (z + r * private_key)) % _N
        if s == 0:
            continue
        return r.to_bytes(32, "big") + s.to_bytes(32, "big")


def generate_keypair():
    """Generates a fresh P-256 keypair entirely on-device, using the same
    os.urandom CSPRNG source as sign(). Returns (private_key, pubkey_bytes):
    private_key is a raw int scalar (see load_device_private_key() in
    common.py), pubkey_bytes is the raw 0x04||X||Y point (65 bytes) verify()
    expects.

    Used by keygen_device.py to provision a device's attestation identity -
    deliberately run here, on the device, rather than on a laptop: the
    private key this returns never has to be written to, or even briefly
    exist in the memory of, any machine other than the one that will use it
    to sign. That's a stronger property than generating it elsewhere and
    copying it over (e.g. the update-signing keypair in keygen.py, which
    has to be laptop-side since server.py itself runs there).
    """
    while True:
        d = int.from_bytes(os.urandom(32), "big") % _N
        if d != 0:
            break
    point = _scalar_mult(d, (_GX, _GY))
    assert point is not None
    pubkey_bytes = b"\x04" + point[0].to_bytes(32, "big") + point[1].to_bytes(32, "big")
    return d, pubkey_bytes
